#!/usr/bin/env node
/**
 * Generates static/js/core/icons.js — the lucide-react surface the app uses.
 *
 * The port has no React, so `<Search size={14} />` needs a component that
 * produces byte-identical SVG markup to lucide's. Rather than hand-copying
 * path data, this reads the real icon nodes out of the pinned lucide-react
 * package and emits plain modules with lucide's own default attributes.
 *
 *   node django/scripts/gen_icons.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const srcDir = join(repo, "frontend", "src");
const lucideIcons = join(repo, "frontend", "node_modules", "lucide-react", "dist", "esm", "icons");
const outFile = join(repo, "django", "static", "js", "core", "icons.js");

const toKebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

/** Every `import { A, B as C } from 'lucide-react'` specifier in the app. */
function collectNames(dir) {
  const found = new Set();
  const walk = (d) => {
    for (const entry of readdir(d)) {
      const full = join(d, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.jsx?$/.test(entry.name)) {
        const code = readFileSync(full, "utf8");
        for (const match of code.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]lucide-react['"]/g)) {
          for (const raw of match[1].split(",")) {
            const name = raw.trim().split(/\s+as\s+/)[0].trim();
            if (name) found.add(name);
          }
        }
      }
    }
  };
  walk(dir);
  return [...found].sort();
}

import { readdirSync, statSync } from "node:fs";
const readdir = (d) =>
  readdirSync(d).map((name) => ({ name, isDirectory: () => statSync(join(d, name)).isDirectory() }));

/** `const __iconNode = [ … ];` → array of [tag, attributes], alias-aware. */
function iconNode(file, seen = new Set()) {
  if (seen.has(file)) throw new Error(`icon alias loop at ${file}`);
  seen.add(file);
  const code = readFileSync(file, "utf8");
  const alias = code.match(/export\s*\{\s*default\s*\}\s*from\s*'\.\/([^']+)\.js'/);
  if (alias) return iconNode(join(lucideIcons, `${alias[1]}.js`), seen);
  const start = code.indexOf("const __iconNode = [");
  if (start === -1) throw new Error(`no __iconNode in ${file}`);
  const from = start + "const __iconNode = ".length;
  let depth = 0;
  let end = from;
  for (let i = from; i < code.length; i++) {
    const ch = code[i];
    if (ch === "[") depth++;
    else if (ch === "]") {
      depth--;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  return new Function(`return ${code.slice(from, end)};`)();
}

const names = collectNames(srcDir);
const blocks = [];
const missing = [];

for (const name of names) {
  // lucide splits trailing digits into their own word: Trash2 → trash-2.js
  const base = toKebab(name);
  const candidates = [base, base.replace(/([a-z])(\d)$/g, "$1-$2")];
  const file = candidates
    .map((candidate) => join(lucideIcons, `${candidate}.js`))
    .find((path) => existsSync(path));
  if (!file) {
    missing.push(name);
    continue;
  }
  const nodes = iconNode(file)
    .map(([tag, attrs]) => {
      const entries = Object.entries(attrs)
        .filter(([key]) => key !== "key")
        .map(([key, value]) => `${key}: ${JSON.stringify(String(value))}`)
        .join(", ");
      return `    ["${tag}", { ${entries} }],`;
    })
    .join("\n");
  blocks.push(`export const ${name} = icon("${name}", [\n${nodes}\n]);`);
}

if (missing.length) console.warn("lucide icons not found:", missing.join(", "));

writeFileSync(
  outFile,
  `/**
 * lucide-react stand-in — generated by django/scripts/gen_icons.mjs from the
 * pinned lucide package, so the SVG output (viewBox, stroke, linecap, node
 * order) is what the design was built against. Do not edit by hand.
 */
import React from "dp/core/react.js";

const DEFAULTS = {
  xmlns: "http://www.w3.org/2000/svg",
  viewBox: "0 0 24 24",
  fill: "none",
  stroke: "currentColor",
  "stroke-linecap": "round",
  "stroke-linejoin": "round",
};

function icon(iconName, iconNode) {
  const Icon = ({
    color = "currentColor",
    size = 24,
    strokeWidth = 2,
    absoluteStrokeWidth,
    className = "",
    children,
    ...rest
  }) =>
    React.createElement(
      "svg",
      {
        ...DEFAULTS,
        width: size,
        height: size,
        stroke: color,
        strokeWidth: absoluteStrokeWidth
          ? (Number(strokeWidth) * 24) / Number(size)
          : strokeWidth,
        className: ["lucide", \`lucide-\${kebab(iconName)}\`, className].filter(Boolean).join(" "),
        ...rest,
      },
      [
        ...iconNode.map(([tag, attrs]) => React.createElement(tag, attrs)),
        ...(Array.isArray(children) ? children : [children]),
      ]
    );
  Icon.displayName = iconName;
  return Icon;
}

const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

${blocks.join("\n\n")}
`
);

console.log(`wrote ${outFile} (${names.length} icons)`);
